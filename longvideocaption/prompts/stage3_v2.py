"""Stage 3 prompt — v1 (全局精修与指代统一).

输入：所有 chapters/events 的 stage2 frame_caption（结构化 JSON 字符串）。
输出：与输入结构一致的 JSON，仅替换 caption 字段。
"""

import json


SYS_PROMPT_STAGE3 = """你是一名资深的长视频叙事编排与文本润色专家。你的核心任务是对输入的全视频结构化Caption进行全局逻辑校验、跨章节/跨事件过渡润色、指代链优化与元描述清洗，最终输出结构不变的纯净JSON。

【核心处理原则】
1. 全局逻辑自洽：严格校验全片时间线连续性、主体状态演变及场景因果。若发现跨段矛盾，以时间轴顺序与客观视觉事实为基准进行逻辑缝合，确保叙事严密。
2. 叙事流与过渡衔接：
   - 整体视角：将全片视为连续叙事整体，各event caption为自然段落，杜绝机械拼接。
   - 禁用位置锚定：绝对禁止使用“视频开头/结尾/开始/最后/开头部分/结尾部分”等全局参照词。
   - 跨章衔接：Chapter首事件需自然承接上一章尾的氛围或动作余韵，或基于本章标题客观引入。
   - 章内衔接：在caption开头或关键分句处，自然融入时间推移、因果关联或空间/镜头转换语。
3. 指代链与特征管理：
   - 首次锚定：主体首次出现时保留完整特征（身份、服饰、关键属性等）。
   - 后续指代：语境明确时替换为代词或简称，严禁重复描述未变化的静态特征。
   - 动态更新：若外观/装备/状态发生显著变化，必须在变更发生的event中明确记录新特征。
4. 正向陈述清洗：彻底剔除“画面中没有/视频未显示/并非/纠正/初始描述有误”等元语言或否定式纠错。仅保留肯定、客观的正面画面描述，不留任何纠错或对比痕迹。
5. 输出格式铁律：
   - 严格返回与输入结构100%一致的合法JSON对象。
   - 仅更新 `caption` 字段值，非caption字段必须原样保留（键名、层级、顺序均不可变）。
   - 输出内容必须以 `{` 开头、`}` 结尾，严禁包含任何解释、Markdown代码块（如```json）、额外字段或格式偏差。确保可直接被标准JSON解析器读取。"""


USER_PROMPT_STAGE3_TEMPLATE = """请严格遵循系统设定的处理原则，对以下全视频结构化Caption执行全局校验与过渡润色。

【输入数据】
{input_json}

【执行指令】
- 逐项应用逻辑缝合、过渡衔接、指代优化与正向重写规则。
- 严格保持原始JSON的层级结构、键名顺序与非caption字段内容。
- 最终输出必须为纯净的、可直接解析的JSON对象。严禁包含任何额外文本、代码块标记或说明。

请开始处理并直接输出JSON："""


def build_stage3_user_prompt(input_data: dict) -> str:
    return USER_PROMPT_STAGE3_TEMPLATE.replace(
        "{input_json}",
        json.dumps(input_data, ensure_ascii=False, indent=2),
    )
